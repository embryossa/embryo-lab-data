"""Cross-run historical tracking of aggregate (never per-patient) metrics.

``data/processed`` is regenerated by every run but is not itself deleted between
runs, so an append-only ``run_history.jsonl`` living there accumulates one
record per run across the project's lifetime. Records hold cohort-level KPI,
calibration and forensic aggregates only — no ``cycle_uid``, no patient-level
rows — so they carry the same privacy posture as the rest of ``data/processed``
and may be read by the same forensics/lead-analyst agents that already read
cohort aggregates from the agent packet.

At small per-run cohort sizes (this project's n is in the tens of cycles),
individual-run confidence intervals are wide. The point of this history is to
let a reader see whether a metric is stable, drifting, or still just noisy
across many runs, rather than re-deriving everything from a single run as if
it were the first.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from . import _io
from .kpi import aggregate_kpis, compute_rates

HISTORY_COLUMNS = (
    "run_id", "created_utc", "input_sha256", "n_cycles", "dnn_status",
    "regression_status", "review_list_n", "ozema_candidates_n", "kpi",
    "miri_baseline", "lot_baseline", "regression_calibration",
)


def _json_safe(value):
    """Recursively convert numpy/pandas scalars so ``json.dumps`` never trips."""
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(v) for v in value]
    if isinstance(value, (np.generic,)):
        value = value.item()
    if isinstance(value, float) and not np.isfinite(value):
        return None
    if isinstance(value, (pd.Timestamp,)):
        return None if pd.isna(value) else value.isoformat()
    if value is pd.NaT:
        return None
    if isinstance(value, float) and pd.isna(value):
        return None
    return value


def _kpi_block(kpi_cycles: pd.DataFrame) -> dict:
    """Cohort-level KPI (sum-numerator/sum-denominator), keyed by metric name."""
    if kpi_cycles is None or kpi_cycles.empty:
        return {}
    d = kpi_cycles.copy() if "_fr_denominator" in kpi_cycles.columns else compute_rates(kpi_cycles)
    table = aggregate_kpis(d)
    keep = ["numerator", "denominator", "rate", "ci_low_95", "ci_high_95", "status", "n_cycles"]
    return {
        str(row["metric"]): {k: _json_safe(row[k]) for k in keep}
        for _, row in table.iterrows()
    }


def _regression_block(regression_calibration: pd.DataFrame | None) -> list[dict]:
    if regression_calibration is None or regression_calibration.empty:
        return []
    keep = [c for c in ["stage", "n_evaluated", "share_in_interval80", "mae_p50"]
            if c in regression_calibration.columns]
    return [{k: _json_safe(row[k]) for k in keep} for _, row in regression_calibration[keep].iterrows()]


def build_record(
    manifest: dict,
    kpi_cycles: pd.DataFrame,
    review_list: pd.DataFrame | None = None,
    miri_baseline: dict | None = None,
    lot_baseline: dict | None = None,
    regression_calibration: pd.DataFrame | None = None,
    ozema_candidates: pd.DataFrame | None = None,
) -> dict:
    """Assemble one privacy-safe history record summarizing a completed run."""
    review_n = int(len(review_list)) if isinstance(review_list, pd.DataFrame) else 0
    ozema_n = (int(ozema_candidates["patient_id"].nunique())
               if isinstance(ozema_candidates, pd.DataFrame) and not ozema_candidates.empty
               and "patient_id" in ozema_candidates.columns else 0)
    return {
        "run_id": manifest.get("run_id"),
        "created_utc": manifest.get("created_utc"),
        "input_sha256": manifest.get("input_sha256"),
        "n_cycles": _json_safe(manifest.get("n_cycles")),
        "dnn_status": manifest.get("dnn_status"),
        "regression_status": manifest.get("regression_status"),
        "review_list_n": review_n,
        "ozema_candidates_n": ozema_n,
        "kpi": _kpi_block(kpi_cycles),
        "miri_baseline": _json_safe(miri_baseline) if miri_baseline else None,
        "lot_baseline": _json_safe(lot_baseline) if lot_baseline else None,
        "regression_calibration": _regression_block(regression_calibration),
    }


def append_record(record: dict, path: str | Path) -> Path:
    """Append one run's record to the jsonl history, atomically rewriting the file.

    Records are small (one run each) and the file is local-only, so a full
    read-modify-atomic-rewrite matches this project's write convention
    (``_io.atomic_write_*``) instead of a bare append that could interleave a
    partial line with a concurrent crash.
    """
    target = Path(path)
    lines = []
    if target.is_file():
        lines = [line for line in target.read_text(encoding="utf-8").splitlines() if line.strip()]
    lines.append(json.dumps(_json_safe(record), ensure_ascii=False))
    _io.atomic_write_text("\n".join(lines) + "\n", target)
    return target


def load_history(path: str | Path) -> pd.DataFrame:
    """Load the run history as one flattened row per run (empty frame if none yet)."""
    target = Path(path)
    if not target.is_file():
        return pd.DataFrame(columns=HISTORY_COLUMNS)
    records = [json.loads(line) for line in target.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not records:
        return pd.DataFrame(columns=HISTORY_COLUMNS)
    return pd.json_normalize(records, sep="_")
